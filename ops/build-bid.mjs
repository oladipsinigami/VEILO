/**
 * Build the bid page's browser bundle.
 *
 *   node ops/build-bid.mjs           write demo/bid/app.js
 *   node ops/build-bid.mjs --check   fail if the committed bundle is stale
 *
 * Why a bundle at all: the bidder's crypto is `web/src/lib/memo.ts`, which
 * imports @noble packages by bare specifier. Browsers do not resolve those, and
 * the project otherwise has no build step. A committed bundle keeps the page
 * static — the same policy as `demo/pkg`, which is a committed wasm-bindgen
 * artefact checked in by CI rather than rebuilt by every visitor.
 *
 * The check mode is what makes that policy safe: if someone edits `memo.ts` and
 * forgets to rebuild, CI fails instead of shipping a page whose sealing code
 * no longer matches the audited reference.
 */

import { build } from "esbuild";
import { readFileSync, mkdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname } from "node:path";

const ENTRY = "web/src/lib/bid-entry.ts";
const OUTFILE = "demo/bid/app.js";
const BANNER =
  "/* Veilo bid bundle — generated by ops/build-bid.mjs from " +
  "web/src/lib/bid-entry.ts. Do not edit by hand. */";

const options = {
  entryPoints: [ENTRY],
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  minify: true,
  legalComments: "none",
  banner: { js: BANNER },
  write: false,
  logLevel: "warning",
};

const result = await build(options);
const output = result.outputFiles?.[0]?.contents;
if (!output) {
  console.error("esbuild produced no output");
  process.exit(1);
}

const check = process.argv.includes("--check");

if (!check) {
  mkdirSync(dirname(OUTFILE), { recursive: true });
  writeFileSync(OUTFILE, output);
  console.log(`wrote ${OUTFILE} (${output.length} bytes)`);
  process.exit(0);
}

if (!existsSync(OUTFILE)) {
  console.error(`::error::${OUTFILE} is missing; run npm run bid:build`);
  process.exit(1);
}

const committed = readFileSync(OUTFILE);
if (Buffer.compare(Buffer.from(output), committed) === 0) {
  console.log(`${OUTFILE} is up to date (${committed.length} bytes)`);
  process.exit(0);
}

console.error(
  `::error::${OUTFILE} is stale (${committed.length} bytes committed, ` +
    `${output.length} bytes built). Run npm run bid:build and commit the result.`
);
process.exit(1);
