/**
 * Generate cross-implementation test vectors from the TypeScript implementation.
 *
 * The bidder's browser packs envelopes in TypeScript; the auditor unpacks them in
 * Rust/WASM. If the two ever disagree on a single byte, every bid becomes
 * unreadable and every audit silently fails. This file is the contract: it is
 * generated here, committed, and replayed by `crates/veilo-core/tests/replay.rs`.
 *
 * Format is deliberately dependency-free (key=value lines) so the Rust side needs
 * no JSON parser.
 *
 *   node test/gen-vectors.mjs
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

import {
  computeBidCommit,
  encodeReveal,
  sealRefundAddress,
  openRefundAddress,
  makeRefundKeypair,
  packMemo,
  unpackMemo,
  isVeiloMemo,
  MEMO_SIZE,
} from "../web/src/lib/memo.ts";

const here = dirname(fileURLToPath(import.meta.url));
const hex = (b) => Buffer.from(b).toString("hex");
const unhex = (s) => new Uint8Array(Buffer.from(s, "hex"));

const cases = [];

// Deterministic key material. Fixed so the vectors are reproducible forever;
// a nonce here is not protecting anything, it is pinning behaviour.
const SK_REFUND = "0707070707070707070707070707070707070707070707070707070707070707";
const ESK_REFUND = "0909090909090909090909090909090909090909090909090909090909090909";
const AUCTION_ID = "11111111111111111111111111111111";
const EPK_BID = "3333333333333333333333333333333333333333333333333333333333333333";
const NONCE = "22222222222222222222222222222222";

const ADDRS = [
  "utest1exampleaddress",
  // A realistic long unified address, near the 216-byte ceiling.
  "utest1qpsw0d7s6e5t7dv8x8yyw5e4v4jh8p5kux6g5v4kthh0nngwh2c5ue2x8p3wxy7qsqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqq7egr7p",
];

// Edge amounts: zero, one zatoshi, large, and the u64 boundary.
const BIDS = [0n, 1n, 2_100_000_000_000_000n, 12_345_678_901n];

let i = 0;
for (const addr of ADDRS) {
  for (const bid of BIDS) {
    const useAad = i % 2 === 0;
    const auctionId = unhex(AUCTION_ID);
    // sealRefundAddress takes the PUBLIC key; openRefundAddress takes the SECRET.
    // Conflating the two is the exact bug this file's self-check exists to catch.
    const { skRefund, pkRefund } = makeRefundKeypair(unhex(SK_REFUND));
    // Pin the ephemeral: the Rust replay seals with this same seed, so a random
    // one here would make the cross-implementation check meaningless.
    const { epkRefund, sealed } = sealRefundAddress(
      pkRefund,
      addr,
      useAad ? auctionId : undefined,
      unhex(ESK_REFUND)
    );

    const bidCommit = computeBidCommit(auctionId, bid, unhex(NONCE), unhex(EPK_BID));
    const reveal = encodeReveal(auctionId, { bidZat: bid, nonce: unhex(NONCE) });

    const fields = {
      auctionId,
      epkBid: unhex(EPK_BID),
      epkRefund,
      bidCommit,
      cRefund: sealed,
    };
    const memo = packMemo(fields);

    // Self-check: the Rust side asserts the same properties, but if TS is wrong we
    // want to know here rather than bake a wrong vector into the file.
    const reopened = openRefundAddress(
      skRefund,
      epkRefund,
      sealed,
      useAad ? auctionId : undefined
    );
    if (reopened !== addr) throw new Error(`case ${i}: TS seal/open round-trip failed`);
    if (!isVeiloMemo(memo)) throw new Error(`case ${i}: memo not recognised`);
    if (memo.length !== MEMO_SIZE) throw new Error(`case ${i}: wrong memo size`);
    const parsed = unpackMemo(memo);
    if (hex(parsed.bidCommit) !== hex(bidCommit)) throw new Error(`case ${i}: unpack mismatch`);

    cases.push(
      [
        `case_${i}`,
        `address=${hex(addr)}`,
        `aad=${useAad ? AUCTION_ID : ""}`,
        `sk_refund=${SK_REFUND}`,
        `esk_refund=${ESK_REFUND}`,
        `pk_refund=${hex(pkRefund)}`,
        `auction_id=${AUCTION_ID}`,
        `nonce=${NONCE}`,
        `epk_bid=${EPK_BID}`,
        `bid_zat=${bid.toString()}`,
        `epk_refund=${hex(epkRefund)}`,
        `bid_commit=${hex(bidCommit)}`,
        `reveal=${hex(reveal)}`,
        `sealed=${hex(sealed)}`,
        `memo=${hex(memo)}`,
        "",
      ].join("\n")
    );
    i++;
  }
}

const header = [
  "# Veilo cross-implementation test vectors.",
  "# Generated by test/gen-vectors.mjs from the TypeScript implementation.",
  "# Replayed by crates/veilo-core/tests/replay.rs. Do not hand-edit.",
  "# If Rust and TypeScript disagree, the browser auditor cannot read a browser-built",
  "# bid, so treat any mismatch here as a release blocker.",
  "",
].join("\n");

const out = join(here, "..", "test", "vectors.txt");
writeFileSync(out, header + cases.join("\n"), "utf8");
console.log(`wrote ${cases.length} vectors to ${out}`);
